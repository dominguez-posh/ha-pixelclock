class Glyph:
    __slots__ = ("rows", "width")

    def __init__(self, rows: list[str]) -> None:
        self.width = max((len(r) for r in rows), default=0)
        self.rows = [r.ljust(self.width, ".") for r in rows]

    def pixels(self):
        """Yield (x, y) of set pixels."""
        for y, row in enumerate(self.rows):
            for x, c in enumerate(row):
                if c == "#":
                    yield x, y

    @property
    def has_descender(self) -> bool:
        return len(self.rows) > CAP_HEIGHT and "#" in "".join(self.rows[CAP_HEIGHT:])


_SPACE = Glyph(["." * SPACE_WIDTH])


@cache
def glyph(char: str) -> Glyph:
    if char == " ":
        return _SPACE
    spec = _GLYPHS.get(char)
    if spec is None:
        # fall back to the unaccented letter, then to "?"
        import unicodedata

        base = unicodedata.normalize("NFKD", char)[:1]
        spec = _GLYPHS.get(base, _GLYPHS[FALLBACK])
    return Glyph(spec.split())


def text_width(text: str, scale: int = 1) -> int:
    """Width in pixels including 1 px (scaled) spacing between glyphs."""
    if not text:
        return 0
    return (sum(glyph(c).width for c in text) + len(text) - 1) * scale


def has_descender(text: str) -> bool:
    return any(glyph(c).has_descender for c in text)
